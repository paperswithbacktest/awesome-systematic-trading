#!/usr/bin/env python3
"""Regenerate the Strategies section of the READMEs from the public catalogue.

Reads the public sitemap of paperswithbacktest.com, opens each strategy page to
get the paper's title and the markets it trades, and writes one table per asset
class between the STRATEGIES markers of README.md, README_ja.md and README_zh.md.

    python scripts/build_strategies_table.py

No token is needed: everything read here is what any visitor sees. Strategies are
listed in alphabetical order, up to TOP_N per asset class. The selection does not
rank by any measured result, so the list says nothing about which strategies
worked; each link opens the paper, its trading rules and its Python.
"""
import html
import json
import re
import sys
import time
import urllib.request
from concurrent.futures import ThreadPoolExecutor
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SITE = "https://paperswithbacktest.com"
START = "<!-- STRATEGIES:START - generated by scripts/build_strategies_table.py -->"
END = "<!-- STRATEGIES:END -->"
TOP_N = 12
WORKERS = 6
# Sections of /strategies that are listings, not strategy pages.
NOT_STRATEGIES = {"dataset", "still-working", "awaiting-data", "page"}

ASSET_ORDER = [
    ("Equities", ("Equities",)),
    ("Bonds", ("Bonds",)),
    ("Commodities", ("Commodities",)),
    ("Currencies", ("Currencies", "Forex")),
    ("Cryptocurrencies", ("Cryptocurrencies",)),
    ("Derivatives", ("Derivatives",)),
    ("Multi-asset", ()),
]

# Paper titles stay in the language they were published in, since they are
# citations. Everything the generator writes around them is translated, so the
# Chinese README does not end up an English one with a Chinese preamble.
LOCALES = {
    "README.md": {
        "buckets": {label: label for label, _ in ASSET_ORDER},
        "header": "| Strategy | Code and backtest |",
        "open": "Open",
        "caveat": (
            "*{shown} published strategies, up to {top} per asset class, in alphabetical "
            "order. Each link opens the paper, its trading rules and its Python on Papers "
            "With Backtest.*"
        ),
    },
    "README_ja.md": {
        "buckets": {
            "Equities": "株式",
            "Bonds": "債券",
            "Commodities": "コモディティ",
            "Currencies": "通貨",
            "Cryptocurrencies": "暗号資産",
            "Derivatives": "デリバティブ",
            "Multi-asset": "マルチアセット",
        },
        "header": "| 戦略 | コードとバックテスト |",
        "open": "開く",
        "caveat": (
            "*公開済みの戦略 {shown} 件を、資産クラスごとに最大 {top} 件、アルファベット順に"
            "掲載しています。各リンクから Papers With Backtest 上の論文、その売買ルール、"
            "Python コードを開けます。*"
        ),
    },
    "README_zh.md": {
        "buckets": {
            "Equities": "股票",
            "Bonds": "债券",
            "Commodities": "大宗商品",
            "Currencies": "外汇",
            "Cryptocurrencies": "加密货币",
            "Derivatives": "衍生品",
            "Multi-asset": "多资产",
        },
        "header": "| 策略 | 代码与回测 |",
        "open": "打开",
        "caveat": (
            "*共 {shown} 个已发布的策略，每类资产最多 {top} 个，按字母顺序排列。每个链接都会在 "
            "Papers With Backtest 上打开论文、其交易规则和 Python 代码。*"
        ),
    },
}


def fetch(url: str, attempts: int = 3) -> str:
    request = urllib.request.Request(url, headers={"User-Agent": "awesome-systematic-trading"})
    for attempt in range(attempts):
        try:
            with urllib.request.urlopen(request, timeout=60) as response:
                return response.read().decode("utf-8", "replace")
        except Exception:  # noqa: BLE001 - a page that will not load is skipped
            if attempt == attempts - 1:
                return ""
            time.sleep(2 * (attempt + 1))
    return ""


def strategy_slugs() -> list[str]:
    sitemap = fetch(f"{SITE}/sitemap.xml")
    slugs = re.findall(rf"<loc>{re.escape(SITE)}/strategies/([^/<]+)</loc>", sitemap)
    return sorted({s for s in slugs if s not in NOT_STRATEGIES})


def paper_title(page: str) -> str:
    """The paper's own title, from the page's structured data."""
    for block in re.findall(r'<script[^>]*type="application/ld\+json"[^>]*>(.*?)</script>', page, re.S):
        try:
            data = json.loads(block)
        except ValueError:
            continue
        based_on = data.get("isBasedOn") if isinstance(data, dict) else None
        if isinstance(based_on, dict) and based_on.get("name"):
            return based_on["name"]
    return ""


def markets_traded(page: str) -> str:
    match = re.search(r">Markets traded</span>\s*<p[^>]*>([^<]*)</p>", page)
    return html.unescape(match.group(1)) if match else ""


def clean_title(title: str) -> str:
    """Papers are stored with their own capitalisation, some of it shouted."""
    title = " ".join(title.split())
    # Footnote marks the PDF title carries (`Machine Learning*`, `Revisited∗`).
    title = re.sub(r"\s*[*∗†‡]+$", "", title)
    letters = [c for c in title if c.isalpha()]
    if letters and sum(c.isupper() for c in letters) / len(letters) > 0.7:
        title = title.title()
    return title.replace("|", "/").replace("*", "\\*").replace("_", "\\_")


def asset_bucket(markets: str) -> str:
    parts = {p.strip() for p in (markets or "").split(",") if p.strip()}
    if not parts:
        return ""
    if len(parts) > 1:
        return "Multi-asset"
    for label, names in ASSET_ORDER:
        if parts & set(names):
            return label
    return ""


def read_strategy(slug: str) -> dict | None:
    page = fetch(f"{SITE}/strategies/{slug}")
    title = clean_title(paper_title(page))
    bucket = asset_bucket(markets_traded(page))
    if not title or not bucket:
        return None
    return {"slug": slug, "title": title, "bucket": bucket}


def sort_key(row: dict) -> tuple[str, str]:
    # Alphabetical on the title, ignoring case and leading quotes or punctuation.
    # Titles in other scripts (Korean, Cyrillic…) sort after Latin ones by code point.
    return (re.sub(r"^[\W_]+", "", row["title"]).casefold(), row["slug"])


def render(rows: list[dict], locale: dict) -> tuple[str, int]:
    blocks, shown = [], 0
    for label, _ in ASSET_ORDER:
        picked = sorted((r for r in rows if r["bucket"] == label), key=sort_key)[:TOP_N]
        if not picked:
            continue
        shown += len(picked)
        blocks += [f"## {locale['buckets'][label]}", "", locale["header"], "|---|---|"]
        for row in picked:
            url = f"{SITE}/strategies/{row['slug']}"
            blocks.append(f"| {row['title']} | [{locale['open']}]({url}) |")
        blocks.append("")

    caveat = locale["caveat"].format(shown=shown, top=TOP_N)
    return "\n".join([START, "", caveat, ""] + blocks + [END]), shown


def main() -> int:
    slugs = strategy_slugs()
    if not slugs:
        print("no strategy found in the sitemap", file=sys.stderr)
        return 1
    print(f"reading {len(slugs):,} strategy pages", file=sys.stderr)
    with ThreadPoolExecutor(max_workers=WORKERS) as pool:
        rows = [r for r in pool.map(read_strategy, slugs) if r]
    if not rows:
        print("no strategy page could be read", file=sys.stderr)
        return 1

    shown = 0
    for name, locale in LOCALES.items():
        readme = ROOT / name
        text = readme.read_text()
        if START not in text:
            print(f"markers not found in {name}", file=sys.stderr)
            return 1
        body, shown = render(rows, locale)
        readme.write_text(
            re.sub(re.escape(START) + r".*?" + re.escape(END), lambda _: body, text, flags=re.S)
        )
    buckets = len({r["bucket"] for r in rows})
    print(f"wrote {shown} rows into {len(LOCALES)} READMEs, "
          f"from {len(rows):,} strategies across {buckets} asset classes")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
